def get_scenarios(mode):
    """获取某模式的所有剧本"""
    return SCENARIOS.get(mode, [])


def get_scenario(mode, scenario_id):
    """获取指定剧本"""
    for s in SCENARIOS.get(mode, []):
        if s["id"] == scenario_id:
            return s
    return None


def add_custom_scenario(mode, scenario_data):
    """添加自定义剧本（AI 生成或联网获取）"""
    if mode not in SCENARIOS:
        SCENARIOS[mode] = []
    SCENARIOS[mode].append(scenario_data)
    return True
